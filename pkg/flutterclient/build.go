package flutterclient

import (
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

// BuildOptions configures BuildWeb.
type BuildOptions struct {
	// Flutter is the flutter executable (default "flutter" on PATH).
	Flutter string
	// Args are extra arguments for `flutter build web` (for example
	// "--wasm" or "--dart-define=API=...").
	Args []string
	// EmbedDir, when set, receives the build as a Go package: the web build
	// in <EmbedDir>/dist and an embed.go exposing it as `FS`, ready for
	// panel.FlutterFS(<package>.FS).
	EmbedDir string
	// Output receives flutter's output (default os.Stdout).
	Output io.Writer
}

// distMarker marks a dist directory written by BuildWeb, so a rebuild only
// ever replaces a directory it created.
const distMarker = ".gofilament-dist"

// BuildWeb runs `flutter build web --release` in appDir (the app's
// <base href> is set by the panel when it serves the build) and, with
// EmbedDir, copies build/web into an embeddable Go package.
func BuildWeb(appDir string, o BuildOptions) error {
	if o.Flutter == "" {
		o.Flutter = "flutter"
	}
	if o.Output == nil {
		o.Output = os.Stdout
	}
	args := append([]string{"build", "web", "--release"}, o.Args...)
	cmd := exec.Command(o.Flutter, args...)
	cmd.Dir = appDir
	cmd.Stdout, cmd.Stderr = o.Output, o.Output
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("flutter build web in %s: %w", appDir, err)
	}
	web := filepath.Join(appDir, "build", "web")
	if _, err := os.Stat(filepath.Join(web, "index.html")); err != nil {
		return fmt.Errorf("flutter build web did not produce %s/index.html", web)
	}
	if o.EmbedDir == "" {
		return nil
	}
	return writeEmbedPackage(web, o.EmbedDir)
}

var notIdent = regexp.MustCompile(`[^a-z0-9_]`)

func writeEmbedPackage(web, dir string) error {
	dist := filepath.Join(dir, "dist")
	if _, err := os.Stat(dist); err == nil {
		if _, err := os.Stat(filepath.Join(dist, distMarker)); err != nil {
			return fmt.Errorf("%s exists and was not written by filament:flutter-build; remove it or choose another --embed directory", dist)
		}
		if err := os.RemoveAll(dist); err != nil {
			return err
		}
	}
	err := filepath.WalkDir(web, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(web, path)
		target := filepath.Join(dist, rel)
		if d.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(target, b, 0o644)
	})
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dist, distMarker), []byte("written by gofilament filament:flutter-build\n"), 0o644); err != nil {
		return err
	}
	pkg := notIdent.ReplaceAllString(strings.ToLower(filepath.Base(filepath.Clean(dir))), "_")
	if pkg == "" || pkg[0] >= '0' && pkg[0] <= '9' {
		pkg = "web" + pkg
	}
	src := fmt.Sprintf(`// Code generated by gofilament filament:flutter-build. DO NOT EDIT.

// Package %s holds the panel's compiled Flutter web app.
package %s

import (
	"embed"
	"io/fs"
)

//go:embed all:dist
var dist embed.FS

// FS is the web build (index.html at its root): panel.FlutterFS(%s.FS).
var FS fs.FS = mustSub()

func mustSub() fs.FS {
	sub, err := fs.Sub(dist, "dist")
	if err != nil {
		panic(err)
	}
	return sub
}
`, pkg, pkg, pkg)
	return os.WriteFile(filepath.Join(dir, "embed.go"), []byte(src), 0o644)
}
