// UITranslations adds or replaces translations of the Flutter app's own
// words for locale, keyed by the English text (for example
// {"Sign in": "Anmelden"}). Placeholders like {n} must be kept.
func (p *Panel) UITranslations(locale string, lines map[string]string) *Panel {
	if p.uiTranslations == nil {
		p.uiTranslations = map[string]map[string]string{}
	}
	if p.uiTranslations[locale] == nil {
		p.uiTranslations[locale] = map[string]string{}
	}
	for k, v := range lines {
		p.uiTranslations[locale][k] = v
	}
	return p
}

// GetUITranslations returns the Flutter app's words for locale: the
// built-in ones (ar, de, es, fr) with the panel's own on top.
func (p *Panel) GetUITranslations(locale string) map[string]string {
	out := map[string]string{}
	base := locale
	if i := strings.IndexAny(locale, "-_"); i > 0 {
		base = locale[:i]
	}
	for _, l := range []string{base, locale} {
		for k, v := range defaultUITranslations[l] {
			out[k] = v
		}
		for k, v := range p.uiTranslations[l] {
			out[k] = v
		}
	}
	return out
}
